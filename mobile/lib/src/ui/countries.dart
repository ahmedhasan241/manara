/// A country for profile forms.
class Country {
  const Country(this.code, this.name, this.nameAr);

  /// ISO 3166-1 alpha-2, e.g. "EG".
  final String code;
  final String name;
  final String nameAr;

  /// The flag emoji, built from the code's regional indicator letters.
  String get flag => countryFlag(code);

  bool matches(String query) {
    final q = query.trim().toLowerCase();
    if (q.isEmpty) return true;
    return code.toLowerCase() == q || name.toLowerCase().contains(q) || nameAr.contains(q);
  }
}

/// "🇪🇬" for "EG"; empty for anything that isn't two letters.
String countryFlag(String? code) {
  if (code == null || !RegExp(r'^[A-Za-z]{2}$').hasMatch(code)) return '';
  return String.fromCharCodes(code.toUpperCase().codeUnits.map((c) => 0x1F1E6 + c - 65));
}

Country? countryByCode(String? code) {
  if (code == null) return null;
  final upper = code.toUpperCase();
  for (final c in countries) {
    if (c.code == upper) return c;
  }
  return null;
}

